export type ImportMessageKey = keyof typeof importMessages

/** Same interpolation as the app's t(): {name} placeholders from params. */
export function ti(key: ImportMessageKey, params?: Record<string, string | number>): string {
  const template: string = importMessages[key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in params ? String(params[name]) : match))
}
